const protect = (source) => {
  const saved = [];
  const save = (value) => {
    const token = `\uE000${String.fromCodePoint(0xE100 + saved.length)}\uE001`;
    saved.push(value);
    return token;
  };
  let value = source.replace(/<[^>]+>|&[A-Za-z0-9#]+;/g, save);
  const literals = [
    ...never.brand,
    ...never.standards,
    ...never.citations,
    ...never.wireAndCableDesignations,
    ...never.unitSymbols,
  ].sort((a, b) => b.length - a.length);
  for (const literal of literals) {
    const escaped = literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    value = value.replace(
      new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, 'gu'),
      () => save(literal),
    );
  }
  value = value
    .replace(/support@voltdrop\.app|https?:\/\/\S+|\$?\d+(?:[.,/-]\d+)*/g, save)
  return {
    value,
    restore: (translated) => translated.replace(
      /\uE000([\uE100-\uEFFF])\uE001/g,
      (_, marker) => saved[marker.codePointAt(0) - 0xE100],
    ),
  };
};

